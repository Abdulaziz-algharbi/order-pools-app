export const joins: Join[] = poolParticipants.map((p, i) => {
  const pool = pools.find((pl) => pl.id === p.poolId)!;
  return {
    id: `join-${i + 1}`,
    poolId: p.poolId,
    retailerId: p.retailerId,
    quantity: p.quantity,
    totalPrice: Math.round(p.quantity * pool.unitPrice * 100) / 100,
    joinedAt: p.joinedAt,
  };
});

